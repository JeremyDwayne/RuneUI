local fakeStore = require("spec/support/fake_store")
local party = require("src/party")
local savedparty = require("src/savedparty")

describe("savedparty", function()
  it("keeps each name's default tag across loads, matching names by party.key and dropping malformed tags", function()
    local store = fakeStore({ partyRoles = { oakhelm = "TOOLONG", brunt = 5, ysolde = "G2" } })
    local s = savedparty.load(store)
    s.setRole("Iron Oak", "BT")
    s.setRole("Tamsin", " dps ")
    s.setRole("Ysolde", "")
    local roles = savedparty.load(store).roles()
    assert.are.same({ ["iron oak"] = "BT", tamsin = "dps" }, roles.defaults)
    assert.is_nil(roles.preset)
    assert.are.equal("BT", party.tag(roles, "iron\u{A0}oak"))
  end)

  it("saves a tag to the active preset, whose tags override defaults until it is turned off", function()
    local store = fakeStore()
    local s = savedparty.load(store)
    s.setRole("Brunt", "DPS")
    local slot = s.addRolePreset("Amascut")
    s.setActiveRolePreset(slot)
    s.setRole("Brunt", "T2")
    local reloaded = savedparty.load(store)
    assert.are.same({ { slot = slot, name = "Amascut" } }, reloaded.rolePresets())
    assert.are.equal(slot, reloaded.activeRolePreset())
    assert.are.equal("T2", party.tag(reloaded.roles(), "Brunt"))
    reloaded.setActiveRolePreset(nil)
    assert.are.equal("DPS", party.tag(reloaded.roles(), "Brunt"))
    assert.are.equal("DPS", party.tag(savedparty.load(store).roles(), "Brunt"))
  end)

  it("holds eight presets, frees a removed preset's slot and turns it off if it was active", function()
    local store = fakeStore()
    local s = savedparty.load(store)
    for i = 1, 8 do
      assert.are.equal(i, s.addRolePreset("Preset " .. i))
    end
    assert.is_nil(s.addRolePreset("One too many"))
    s.setActiveRolePreset(3)
    s.removeRolePreset(3)
    assert.is_nil(s.activeRolePreset())
    assert.is_nil(s.roles().preset)
    assert.are.equal(3, s.addRolePreset("Vorago"))
    local reloaded = savedparty.load(store)
    assert.are.equal(8, #reloaded.rolePresets())
    assert.are.equal("Vorago", reloaded.rolePresets()[3].name)
  end)

  it("keeps each tier's size, columns and Show my frame, dropping values out of range", function()
    local store =
      fakeStore({ party = { tiers = { duo = { w = 9000, columns = 3.0, showSelf = "yes" } }, active = 2.0 } })
    local s = savedparty.load(store)
    assert.are.same({ w = 112, h = 46, columns = 3, rows = 2, showSelf = false }, s.partyTiers().duo)
    assert.is_nil(s.activeRolePreset())
    s.setPartyTier("duo", "showSelf", true)
    s.setPartyTier("raid", "w", 70)
    local tiers = savedparty.load(store).partyTiers()
    assert.is_true(tiers.duo.showSelf)
    assert.are.same({ w = 70, h = 22, columns = 5, rows = 5, showSelf = true }, tiers.raid)
  end)

  it("keeps how the grid fills and grows, with the default for a value it does not know", function()
    local store = fakeStore({ party = { grid = { fill = "columns", growX = "sideways" } } })
    local s = savedparty.load(store)
    assert.are.same({ fill = "columns", growX = "right", growY = "down" }, s.partyGrid())
    s.setPartyGrid("growY", "up")
    assert.are.same({ fill = "columns", growX = "right", growY = "up" }, savedparty.load(store).partyGrid())
  end)

  it("keeps the sidebar on and open until changed, and saves once per change", function()
    local store = fakeStore()
    local s = savedparty.load(store)
    assert.are.same({ on = true, collapsed = false }, s.sidebar())
    assert.are.equal(0, store.writes)
    s.setSidebar("collapsed", true)
    s.setRole("Brunt", "DPS")
    assert.are.equal(2, store.writes)
    assert.are.same({ on = true, collapsed = true }, savedparty.load(store).sidebar())
  end)
end)
